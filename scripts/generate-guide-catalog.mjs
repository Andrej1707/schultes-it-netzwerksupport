import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { securityGuides } from '../src/content/guides/security.ts'
import { windowsGuides } from '../src/content/guides/windows.ts'
import { networkGuides } from '../src/content/guides/network.ts'
import { dataGuides } from '../src/content/guides/data.ts'
import { everydayGuides } from '../src/content/guides/everyday.ts'
import { securityExpansionGuides } from '../src/content/guides/securityExpansion.ts'
import { windowsExpansionGuides } from '../src/content/guides/windowsExpansion.ts'
import { networkExpansionGuides } from '../src/content/guides/networkExpansion.ts'
import { dataExpansionGuides } from '../src/content/guides/dataExpansion.ts'
import { everydayExpansionGuides } from '../src/content/guides/everydayExpansion.ts'

const articles = [
  ...securityGuides, ...securityExpansionGuides,
  ...windowsGuides, ...windowsExpansionGuides,
  ...networkGuides, ...networkExpansionGuides,
  ...dataGuides, ...dataExpansionGuides,
  ...everydayGuides, ...everydayExpansionGuides,
]
if (articles.length !== 70 || new Set(articles.map(article => article.slug)).size !== 70) {
  throw new Error('Expected exactly 70 unique guides.')
}
for (const category of ['sicherheit', 'windows', 'wlan', 'daten', 'alltag']) {
  if (articles.filter(article => article.category === category).length !== 14) {
    throw new Error(`Expected 14 guides in category ${category}.`)
  }
}
const imageHashes = await Promise.all(articles.map(async article => createHash('sha256')
  .update(await readFile(new URL(`../public/images/${article.image}-1280.webp`, import.meta.url)))
  .digest('hex')))
if (new Set(articles.map(article => article.image)).size !== 70 || new Set(imageHashes).size !== 70) {
  throw new Error('Every guide needs its own image; reused images and renamed copies are not allowed.')
}
const summaries = articles.map(({ slug, title, description, category, readMinutes, image, imageAlt, updated }) =>
  ({ slug, title, description, category, readMinutes, image, imageAlt, updated }))
const output = `// Generated by npm run guides:catalog. Full article text is kept out of the client bundle.\nimport type { GuideSummary } from './types'\n\nexport const guideCatalog: GuideSummary[] = ${JSON.stringify(summaries, null, 2)}\n`
const destination = new URL('../src/content/guides/catalog.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')).replaceAll('\r\n', '\n') !== output) throw new Error('Guide catalog is stale. Run npm run guides:catalog.')
  console.log(`Guide catalog matches all ${articles.length} articles.`)
} else {
  await writeFile(destination, output)
  console.log(`Generated metadata for ${articles.length} guides.`)
}
